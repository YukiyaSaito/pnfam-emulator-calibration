#!/usr/bin/env python3
"""Table of the adopted Q-value correction per functional (draft/tables/table_qcorr.tex).

Q_corr = Q_HFB - [a + b (N-Z) + c (N+Z)]; a, b, c from the header of Qsurvey/results/q_shift_<F>.txt
(unweighted least-squares fit of Q_HFB - Q_exp over the 154 even-even nuclei with a measured AME2020 Q).
Columns: mean and sd of Q_HFB - Q_exp before the correction, a, b, c, and sigma_Q = sd after the
correction, all over the same 154 nuclei (Qsurvey/results/dQ_<F>.txt, rows with Qsrc = AME).
sd = population sd (divide by n), the definition of Qsurvey/q_correction.py. sigma_Q is printed from
q_correction.sigma_q() -- the value written into calibration/analysis/sigma_q_<F>.dat and used by every
calibration and N = 126 prediction -- and checked against the recomputed sd (2026-11-03; before, the
n-1 sd printed 0.57 instead of 0.56 MeV for UNEDF1-HFB).
"""
import os
import re
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
import repo_paths as RP  # noqa: E402  (all data paths of the repository)
sys.path.insert(0, RP.QCORR)
import q_correction   # single source of the adopted (a, b, c, sigma_Q)

RES = RP.QCORR_RESULTS
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tables", "table_qcorr.tex")
FUNCS = [("SKOP", r"SkO$'$"), ("SLY4", "SLy4"), ("HFB1", "UNEDF1-HFB")]

lines = ["% Generated by draft/scripts/table_qcorr.py -- do not edit by hand.",
         r"\begin{table}[t]",
         r"\caption{\label{tab:qcorr}%",
         r"Linear correction of the calculated $Q_\beta$ values, Eq.~(\ref{eq:qcorr}), for each functional:",
         r"mean and standard deviation of $Q^{\rm HFB}_\beta-Q^{\rm exp}_\beta$ before the correction, the fitted",
         r"coefficients, and the residual standard deviation $\sigma_Q$ after the correction, over the 154",
         r"even-even nuclei with a measured $Q_\beta$ in AME2020~\cite{AME2020}. All values in MeV.}",
         r"\begin{ruledtabular}",
         r"\begin{tabular}{lccccc}",
         r"Functional & before & $a$ & $b$ & $c$ & $\sigma_Q$ \\",
         r"\colrule"]
for F, lab in FUNCS:
    txt = open(os.path.join(RES, f"q_shift_{F}.txt")).read()
    a, b, c = [float(re.search(k + r"=([+-]?[\d.]+)", txt).group(1)) for k in "abc"]
    rows = [t for t in (l.split() for l in open(os.path.join(RES, f"dQ_{F}.txt"))) if t and t[0].isdigit() and t[11] == "AME"]
    Z = np.array([float(t[0]) for t in rows]); N = np.array([float(t[1]) for t in rows]); dq = np.array([float(t[6]) for t in rows])
    assert len(rows) == 154, (F, len(rows))
    res = dq - (a + b * (N - Z) + c * (N + Z))
    sq = q_correction.sigma_q(F)   # MeV, value used in the calibration
    assert abs(res.std() - sq) < 1e-3, (F, res.std(), sq)
    lines.append(rf"{lab} & ${dq.mean():+.2f} \pm {dq.std():.2f}$ & ${a:+.3f}$ & ${b:+.4f}$ & ${c:+.4f}$ & {sq:.2f} \\")
    print(F, f"before {dq.mean():+.3f} +- {dq.std():.3f} | a {a:+.4f} b {b:+.5f} c {c:+.5f} | sigma_Q {sq:.3f} (recomputed {res.std():.4f}, mean after {res.mean():+.4f})")
lines += [r"\end{tabular}", r"\end{ruledtabular}", r"\end{table}"]
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", os.path.abspath(OUT))
