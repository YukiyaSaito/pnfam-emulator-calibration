#!/usr/bin/env python3
"""Pool tables for the paper: half-life nuclei (42) and GT nuclei (8), with
the experimental values used in the likelihood and the HFB ground-state
quadrupole deformation per functional.

Sources
  experimental values : Beta_decay/config.py (HL_EXP, HL_ERR; GT_E_EXP, GT_E_ERR)
  pool / exclusions   : config.HL_SET_POOL42, config.HL_EXCL_QCORR (two thin
                        sets per functional, 2026-10-08)
  beta2, HL nuclei    : calibration/analysis/nuclei_tag_table[_<F>].csv (beta2
                        column, sample_1 ground state, 2026-10-12)
  beta2, GT nuclei    : ../data/gt_beta2_sample1.txt (extracted 2026-10-13)
Output: ../tables/table_pool_nuclei.tex  (\\input it in main.tex)
"""
import csv
import math
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
import repo_paths as RP  # noqa: E402  (all data paths of the repository)
sys.path.insert(0, RP.CALIBRATION)
import config

HERE = os.path.dirname(os.path.abspath(__file__))
ANA = RP.DESIGN
OUT = os.path.join(HERE, "..", "tables", "table_pool_nuclei.tex")
GT_B2 = os.path.join(HERE, "..", "data", "gt_beta2_sample1.txt")

FUNCS = ["SKOP", "SLY4", "HFB1"]
HEAD = {"SKOP": r"SkO$'$", "SLY4": "SLy4", "HFB1": "UNEDF1-HFB"}
TAG = {"SKOP": "nuclei_tag_table.csv", "SLY4": "nuclei_tag_table_SLY4.csv",
       "HFB1": "nuclei_tag_table_HFB1.csv"}
GT_ORDER = ["Ca48", "Ge76", "Zr90", "Sn112", "Sn132", "Te130", "Nd150", "Pb208"]


def split(name):
    sym = "".join(c for c in name if c.isalpha())
    A = int("".join(c for c in name if c.isdigit()))
    return sym, A


def latex_nuc(name):
    sym, A = split(name)
    return rf"$^{{{A}}}${sym}"


def _sig(e):
    """Significant digits kept for an uncertainty: 2 if its leading digit is 1, else 1."""
    lead = int(f"{e:e}"[0])
    return 2 if lead == 1 else 1


def fmt_pm(x, e):
    """value +- error, error rounded to 1 significant digit (2 if it starts with 1),
    value to the same decimal place; scientific notation for values >= 1e4."""
    if x >= 1e4:
        n = int(math.floor(math.log10(x)))
        xm, em = x / 10**n, e / 10**n
        d = -int(math.floor(math.log10(em))) + _sig(em) - 1
        return rf"$({xm:.{d}f} \pm {em:.{d}f})\times10^{{{n}}}$"
    d = -int(math.floor(math.log10(e))) + _sig(e) - 1
    d = max(d, 0)
    return rf"${x:.{d}f} \pm {e:.{d}f}$"


def fmt_b2(b):
    b = float(b)
    if abs(b) < 0.0005:
        return "0.000"
    return f"{b:+.3f}"


def fmt_b2_hl(b):
    """Two decimals for the half-life table (user 2026-11-16), rounded half away from zero from the
    four-decimal tag-table value; |beta2| < 0.005 printed as 0.00."""
    from decimal import Decimal, ROUND_HALF_UP
    b = float(b)
    if abs(b) < 0.005:
        return "0.00"
    r = Decimal(str(abs(b))).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
    return ("+" if b > 0 else "-") + str(r)


# ---- half-life nuclei --------------------------------------------------------
tags = {F: {r["nucleus"]: r for r in csv.DictReader(open(os.path.join(ANA, TAG[F])))} for F in FUNCS}
pool = sorted(config.HL_SET_POOL42, key=lambda n: (int(tags["SKOP"][n]["Z"]), int(tags["SKOP"][n]["N"])))
assert len(pool) == 42

lines = []
lines.append("% Generated by draft/scripts/table_pool_nuclei.py -- do not edit by hand.")
lines.append(r"\begin{table*}[t]")
lines.append(r"\caption{\label{tab:pool_hl}%")
lines.append(r"Nuclei whose $\beta$-decay half-lives are part of the calibration pool, and their")
lines.append(r"experimental half-lives and uncertainties from Ref.~\cite{Kondev2021}, as well as the predicted quadrupole")
lines.append(r"deformation $\beta_2$ of the HFB ground state obtained with each functional (I=SkO$'$, II=SLy4, III=UNEDF1-HFB).")
lines.append(r"A dagger marks the two nuclei per functional that are")
lines.append(r"excluded from that functional's pool because their decay rates fall below the resolution of the")
lines.append(r"calculation (Sec.~\ref{subsec:optimal_sets}).}")
lines.append(r"\begin{ruledtabular}")
lines.append(r"\begin{tabular}{lrrrrrrr}")
lines.append(r"Nucleus & $Z$ & $N$ & $A$ & $T_{1/2}^{\rm exp}$ (s) & " +
             " & ".join(rf"$\beta_2$({lab})" for lab in ("I", "II", "III")) + r" \\")   # 2026-11-16 (user): roman labels
lines.append(r"\colrule")
for n in pool:
    t = tags["SKOP"][n]
    cells = [latex_nuc(n), t["Z"], t["N"], t["A"], fmt_pm(config.HL_EXP[n], config.HL_ERR[n])]
    for F in FUNCS:
        b = fmt_b2_hl(tags[F][n]["beta2"])
        if n in config.HL_EXCL_QCORR[F]:
            b += r"$^\dagger$"
        cells.append(b)
    lines.append(" & ".join(cells) + r" \\")
lines.append(r"\end{tabular}")
lines.append(r"\end{ruledtabular}")
lines.append(r"\end{table*}")
lines.append("")

# ---- GT nuclei ----------------------------------------------------------------
gtb2 = {}
for ln in open(GT_B2):
    if ln.startswith("#") or not ln.strip():
        continue
    p = ln.split()
    gtb2[p[0]] = dict(zip(FUNCS, p[1:4]))
ZN = {"Ca48": (20, 28), "Ge76": (32, 44), "Zr90": (40, 50), "Sn112": (50, 62),
      "Sn132": (50, 82), "Te130": (52, 78), "Nd150": (60, 90), "Pb208": (82, 126)}
GT_REF = {"Ca48": "Ca48GT", "Ge76": "Ge76Te130GT", "Zr90": "Zr90GT", "Sn112": "Sn112GT",
          "Sn132": "Sn132GT", "Te130": "Ge76Te130GT", "Nd150": "Nd150GT", "Pb208": "Pb208GT"}  # bibl.bib keys

lines.append(r"\begin{table*}[t]")   # full width (hand edit of 2026-10-13 carried into the script)
lines.append(r"\caption{\label{tab:pool_gt}%")
lines.append(r"Nuclei whose Gamow--Teller strength distributions enter the calibration,")
lines.append(r"with the experimental Gamow--Teller resonance peak energies, their uncertainties, and their sources.")
lines.append(r"Predicted $\beta_2$ as in Table~\ref{tab:pool_hl}.}")
lines.append(r"\begin{ruledtabular}")
lines.append(r"\begin{tabular}{lrrrrcrrr}")
lines.append(r"Nucleus & $Z$ & $N$ & $A$ & $E_{\rm GT}^{\rm exp}$ (MeV) & Ref. & " +
             " & ".join(rf"$\beta_2$({lab})" for lab in ("I", "II", "III")) + r" \\")   # 2026-11-16 (user): as Table IV
lines.append(r"\colrule")
for n in GT_ORDER:
    key = n  # config keys use 'Ca_48' style for GT
    ckey = f"{split(n)[0]}_{split(n)[1]}"
    e, de = config.GT_E_EXP[ckey], config.GT_E_ERR[ckey]
    Z, N = ZN[n]
    cells = [latex_nuc(n), str(Z), str(N), str(Z + N), rf"${e:.1f} \pm {de:g}$",
             rf"\cite{{{GT_REF[n]}}}"]
    cells += [fmt_b2_hl(gtb2[n][F]) for F in FUNCS]
    lines.append(" & ".join(cells) + r" \\")
lines.append(r"\end{tabular}")
lines.append(r"\end{ruledtabular}")
lines.append(r"\end{table*}")

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", os.path.abspath(OUT), f"({len(pool)} HL rows, {len(GT_ORDER)} GT rows)")
