#!/usr/bin/env python3
"""Ground-state properties of the N = 126 isotones used in the predictions, per functional:
HFB Q_beta before and after the Q correction, and the quadrupole deformation beta_2.

Source: the production archives of the N = 126 batch 30001 (one run per nucleus is enough: the
even-even HFB ground state does not depend on V0 or C1s, so Energy, Def and HFB_Qval are the same
in all 20 runs; Q_corr is checked against the batch table used for the predictions).
  <scratch>/<F>/outputs/rates/<nuc>_sample_30001_final.tar.gz : <nuc>/sample_30001/meta/logfile_master.dat
      columns Energy [MeV], Def (beta_2), HFB_Qval [MeV] (uncorrected Q = EQRPA_max - E_gs)
  Q correction: FRIB_projects/Qsurvey/q_correction.py dq_model(F, Z, N) (Q_corr = Q_HFB - dq_model)
  check: calibration/<F>/HL/<nuc>/batch30001/halflives_batch30001.txt column Q_corr
Cache: ../data/n126_gs.txt (rewritten on every run). Output: ../tables/table_n126_gs.tex
"""
import io
import os
import subprocess
import sys

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
import repo_paths as RP  # noqa: E402  (all data paths of the repository)
sys.path.insert(0, RP.QCORR)
from q_correction import dq_model  # noqa: E402
from make_nucleus_list import read_ame, AME  # noqa: E402   AME2020 mass table (data/mass_1.mas20.txt)

HERE = os.path.dirname(os.path.abspath(__file__))
SCRATCH = RP.PNFAM_RAW    # raw pnFAM outputs (companion archive); only needed when the cache is missing
OUT = os.path.join(HERE, "..", "tables", "table_n126_gs.tex")
CACHE = os.path.join(HERE, "..", "data", "n126_gs.txt")
FUNCS = ["SKOP", "SLY4", "HFB1"]
HEAD = {"SKOP": r"SkO$'$", "SLY4": "SLy4", "HFB1": "UNEDF1-HFB"}
NUCS = ["Ba182", "Ce184", "Nd186", "Sm188", "Gd190", "Dy192", "Er194", "Yb196", "Hf198", "W200", "Os202", "Pt204", "Hg206"]
ZOF = {n: 56 + 2 * i for i, n in enumerate(NUCS)}
NN = 126
SAMPLE = 30001
# AME2020 Q(beta-) [keV] -> (A, El, Q, dQ, is_systematics); only Os202 (#), Pt204 (#), Hg206 (measured) exist at N = 126
AME2020 = read_ame(AME)


def logfile_row(F, nuc):
    tgz = os.path.join(SCRATCH, F, "outputs", "rates", f"{nuc}_sample_{SAMPLE}_final.tar.gz")
    member = f"{nuc}/sample_{SAMPLE}/meta/logfile_master.dat"
    txt = subprocess.run(["tar", "xzf", tgz, "-O", member], check=True, capture_output=True, text=True).stdout
    lines = [l for l in txt.splitlines() if l.strip()]
    head = lines[0].split()
    vals = lines[1].split()
    # the row has one more leading token (row index) than the header
    row = dict(zip(head, vals[len(vals) - len(head):]))
    return float(row["Energy"]), float(row["Def"]), float(row["HFB_Qval"]), float(row["E_gs"]), row["HFB_Conv"]


def batch_qcorr(F, nuc):
    f = os.path.join(RP.N126, F, nuc, f"batch{SAMPLE}", f"halflives_batch{SAMPLE}.txt")
    q = [float(l.split()[5]) for l in open(f) if not l.startswith("#") and l.strip()]
    return float(np.median(q)), float(np.ptp(q))


def fmt_b2(b):
    return "0.000" if abs(b) < 0.0005 else f"{b:+.3f}"


CACHED = {}
if not SCRATCH:
    for ln in open(CACHE):
        t = ln.split('\t')
        if ln.startswith('#') or t[0] == 'functional':
            continue
        CACHED[(t[0], t[1])] = (float(t[4]), float(t[5]), float(t[6]), t[10].strip())
rows = {}
cache = ["# Ground-state properties of the N = 126 isotones (draft/scripts/table_n126_gs.py); batch 30001, sample 30001",
         "# Q_HFB = uncorrected HFB Q_beta [MeV] (logfile_master HFB_Qval); Q_corr = Q_HFB - dq_model(F,Z,N) [MeV];",
         "# Q_corr_batch = median over the 20 runs in the batch table (ptp = spread); E = HFB energy [MeV]; beta2 = Def",
         "functional\tnucleus\tZ\tN\tE_HFB\tbeta2\tQ_HFB\tQ_corr\tQ_corr_batch\tptp_batch\thfb_conv"]
for F in FUNCS:
    for nuc in NUCS:
        if SCRATCH:
            E, b2, qhfb, egs, conv = logfile_row(F, nuc)
        else:   # no raw archives: take the HFB rows from the committed cache (written by a run with PNFAM_RAW set)
            E, b2, qhfb, conv = CACHED[(F, nuc)]; egs = float('nan')
        qc = qhfb - dq_model(F, ZOF[nuc], NN)
        qb, ptp = batch_qcorr(F, nuc)
        assert abs(qc - qb) < 2e-3, (F, nuc, qc, qb)
        assert ptp < 1e-3, (F, nuc, ptp)
        rows[(F, nuc)] = (E, b2, qhfb, qc)
        cache.append("\t".join([F, nuc, str(ZOF[nuc]), str(NN), f"{E:.6f}", f"{b2:.6f}", f"{qhfb:.6f}",
                                f"{qc:.3f}", f"{qb:.3f}", f"{ptp:.1e}", conv]))
if SCRATCH:
    os.makedirs(os.path.dirname(CACHE), exist_ok=True)
    open(CACHE, "w").write("\n".join(cache) + "\n")

lines = ["% Generated by draft/scripts/table_n126_gs.py -- do not edit by hand.",
         r"\begin{table*}[t]",
         r"\caption{\label{tab:n126_gs}%",
         r"HFB ground-state properties of the even-even $N=126$ isotones with each functional: the $\beta$-decay",
         r"$Q$ value before ($Q_\beta^{\rm HFB}$) and after ($Q_\beta^{\rm corr}$) the correction of Sec.~\ref{subsec:qcorr}, in MeV,",
         r"compared with the AME2020 values~\cite{AME2020} where available (\# marks values from systematics,",
         r"not measured). All ground states are spherical ($|\beta_2|<0.001$).}",
         r"\begin{ruledtabular}",
         r"\begin{tabular}{lr" + "rr" * len(FUNCS) + "r}",
         r" & & " + " & ".join(rf"\multicolumn{{2}}{{c}}{{{HEAD[F]}}}" for F in FUNCS) + r" & AME2020 \\",
         r"Nucleus & $Z$ & " + " & ".join(r"$Q_\beta^{\rm HFB}$ & $Q_\beta^{\rm corr}$" for _ in FUNCS) + r" & $Q_\beta^{\rm exp}$ \\",
         r"\colrule"]
for nuc in NUCS:
    sym = "".join(c for c in nuc if c.isalpha()); A = "".join(c for c in nuc if c.isdigit())
    cells = [rf"$^{{{A}}}${sym}", str(ZOF[nuc])]
    for F in FUNCS:
        E, b2, qhfb, qc = rows[(F, nuc)]
        cells += [f"{qhfb:.2f}", f"{qc:.2f}"]   # beta2 column dropped: all |beta2| < 0.001 (stated in the caption)
    ame = AME2020.get((ZOF[nuc], NN))
    if ame is None:
        cells.append("--")
    else:
        _, _, q, dq, syst = ame
        cells.append(rf"${q/1e3:.2f} \pm {dq/1e3:.2f}$" + (r"\#" if syst else ""))
    lines.append(" & ".join(cells) + r" \\")
lines += [r"\end{tabular}", r"\end{ruledtabular}", r"\end{table*}"]
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", os.path.abspath(OUT), "and", os.path.abspath(CACHE))
for F in FUNCS:
    b2 = [rows[(F, n)][1] for n in NUCS]
    print(F, "beta2 range", f"{min(b2):+.3f} .. {max(b2):+.3f}", "| Q_corr Ba182/Pt204/Hg206",
          " ".join(f"{rows[(F, n)][3]:.2f}" for n in ("Ba182", "Pt204", "Hg206")))
