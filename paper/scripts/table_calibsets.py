#!/usr/bin/env python3
"""Calibration-set table for the paper, generated from Beta_decay/config.py.

Rows per functional: Set A (literature baseline, HL Set A + GT Set A), Full (the 40-nucleus pool),
G10 (global sensitivities) and A10 (sensitivities inside the Set-A posterior
window); V7Q keys (2026-11-05, selected with sigma_Q,i in the information matrix):
G10_SKOP/L10_SKOP, G10_SLY4/L10_SLY4, G10_HFB1/L10_HFB1.
Output: ../tables/table_calibsets.tex  (\\input it in main.tex)
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
import repo_paths as RP  # noqa: E402  (all data paths of the repository)
sys.path.insert(0, RP.CALIBRATION)
import config

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tables", "table_calibsets.tex")

FUNCS = [("SKOP", r"SkO$'$", "G10_SKOP", "L10_SKOP"),
         ("SLY4", "SLy4", "G10_SLY4", "L10_SLY4"),
         ("HFB1", "UNEDF1-HFB", "G10_HFB1", "L10_HFB1")]


def mass(n):
    return int("".join(c for c in n if c.isdigit()))


def latex_list(names):
    names = sorted({n.replace("_", "") for n in names}, key=mass)
    return ", ".join(rf"$^{{{mass(n)}}}${''.join(c for c in n if c.isalpha())}" for n in names)


def latex_lines(names, per_line=8):
    """latex_list split into lines of at most per_line nuclei (continuation rows)."""
    items = latex_list(names).split(", ")
    chunks = [items[i:i + per_line] for i in range(0, len(items), per_line)]
    return [", ".join(c) + ("," if i < len(chunks) - 1 else "") for i, c in enumerate(chunks)]


# Plain l columns; text longer than one line continues on the next row. No p columns: REVTeX 4.2
# replaces the array package's column-preamble code with copies of older internals, which fail on
# p columns with newer array versions (Overleaf, 2026-11-04).
def row(c1, c2, c3, c4):
    c3, c4 = ([c] if isinstance(c, str) else c for c in (c3, c4))
    n = max(len(c3), len(c4))
    c3, c4 = c3 + [""] * (n - len(c3)), c4 + [""] * (n - len(c4))
    return [rf"{c1 if i == 0 else ' '} & {c2 if i == 0 else ' '} & {c3[i]} & {c4[i]} \\" for i in range(n)]


hl_A = config.select_hl_nuclei("A")
gt_A = config.GT_SETS["A"]
lines = ["% Generated by draft/scripts/table_calibsets.py -- do not edit by hand.",
         r"\begin{table*}[t]",
         r"\caption{\label{tab:calibsets}%",
         r"Calibration sets, which consist of $\beta$-decay half-life (HL) nuclei and Gamow--Teller",
         r"resonance (GT) nuclei. Set A is the literature baseline of Ref.~\cite{MustonenEngel},",
         r"common to all functionals. The optimal sets G10 (sensitivities over the full parameter domain)",
         r"and L10 (sensitivities evaluated within the Set A posterior interval of $V_0$) are selected independently",
         r"for each functional. The Full set contains every pool nucleus of the functional.}",
         r"\begin{ruledtabular}",
         r"\begin{tabular}{llll}",
         *row("Functional", "Set", "Half-life nuclei", "GT-resonance nuclei"),
         r"\colrule"]
first = True
for key, label, g8, a8 in FUNCS:
    hl_g, hl_a = config.select_hl_nuclei(g8), config.select_hl_nuclei(a8)
    gt_g = config.GT_SETS[g8]
    if not first:
        lines.append(r"\colrule")
    # functional name on the middle (G10) row of its block
    if first:
        lines += row(" ", "A", latex_lines(hl_A), latex_list(gt_A))
    else:
        lines += row(" ", "A", r"same as SkO$'$", r"same as SkO$'$")
    lines += row(label, "G10", latex_lines(hl_g), r"all eight nuclei of Table~\ref{tab:pool_gt}")
    if set(hl_a) == set(hl_g):
        lines += row(" ", "L10", "same as G10", "same as G10")
    else:
        lines += row(" ", "L10", latex_lines(hl_a), "same as G10")
    npool = len(config.select_hl_nuclei(f"POOL40_{key}"))
    lines += row(" ", "Full", [rf"all {npool} nuclei of Table~\ref{{tab:pool_hl}} not marked for this", "functional"],
                   "same as G10")
    first = False
    print(label, "G10:", latex_list(hl_g).replace("$", ""), "| L10 same" if set(hl_a) == set(hl_g) else "| L10: " + latex_list(hl_a).replace("$", ""))
lines += [r"\end{tabular}", r"\end{ruledtabular}", r"\end{table*}"]
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", os.path.abspath(OUT))
