#!/usr/bin/env python3
"""Posterior summary table for the paper, generated from the MCMC traces.

Rows: functional x set x likelihood. Columns: V0, C1s, sigma_th^HL, sigma_th^GT
as posterior median (16%, 84%).

Runs (2026-10-19):
  Set A   : FINAL-settings Set A runs results/<F>/bayes_<lik>_sthe1_domw10_q_A[_<F>]_sem21001/centroid
            (2026-10-19; Q term, test errors; GT = Set A six nuclei; the anchor fits are no longer shown)
  G10/L10/Full: FINAL runs results/<F>/bayes_<lik>_sthe1_domw10_q_<set>_gtall[_<F>]_sem21001/centroid
            (Q term, test emulator errors; Student-t(4) and Normal)
Output: ../tables/table_posteriors.tex  (\\input it in main.tex)
"""
import csv
import os

import sys
import numpy as np
import xarray as xr
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
import repo_paths as RP  # noqa: E402  (all data paths of the repository)
sys.path.insert(0, RP.CALIBRATION)
import config

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tables", "table_posteriors.tex")

FUNCS = [("SKOP", r"SkO$'$", ""), ("SLY4", "SLy4", "_SLY4"), ("HFB1", "UNEDF1-HFB", "_HFB1")]
# paper sets (keys of calibration/config.py)
SETS = {"SKOP": [("G10", "G10_SKOP"), ("L10", "L10_SKOP"), ("Full", "POOL40_SKOP")],
        "SLY4": [("G10", "G10_SLY4"), ("L10", "L10_SLY4"), ("Full", "POOL40_SLY4")],
        "HFB1": [("G10", "G10_HFB1"), ("L10", "L10_HFB1"), ("Full", "POOL40_HFB1")]}
LIKS = [("t4gtt4", "Student-$t$"), ("norm", "Normal")]
VARS = [("vpair", 0), ("cs0", 1), ("sigma_hl_the", 2), ("sigma_gt_the", 2)]


def stats(d):
    post = xr.open_dataset(os.path.join(d, "trace.nc"), group="posterior")
    rows = list(csv.DictReader(open(os.path.join(d, "summary.csv"))))
    rhat = max(float(r["r_hat"]) for r in rows if r.get("r_hat"))
    out = []
    for v, nd in VARS:
        x = post[v].values.ravel()
        lo, med, hi = np.percentile(x, [16, 50, 84])
        out.append(rf"${med:.{nd}f}$ $({lo:.{nd}f},\,{hi:.{nd}f})$")
    return out, rhat


lines = ["% Generated by draft/scripts/table_posteriors.py -- do not edit by hand.",
         r"\begin{table*}[t]",
         r"\caption{\label{tab:posteriors}%",
         r"Summary of the calibration posteriors: medians with the 16\% and 84\% quantiles in parentheses.",
         r"$V_0$ and $C_1^s$ in MeV\,fm$^3$, $\sigma^{\rm HL}_{\rm th}$ in $\log_{10}(T_{1/2}/{\rm s})$, $\sigma^{\rm GT}_{\rm th}$ in MeV.",
         r"All calibrations include the test emulator errors and the $Q_\beta$ errors. The Set A rows use the",
         r"six GT nuclei of Set A, and all others the eight GT nuclei of Table~\ref{tab:pool_gt}.}",
         r"\begin{ruledtabular}",
         r"\begin{tabular}{lllcccc}",
         r"Functional & Set & Likelihood & $V_0$ & $C_1^s$ & $\sigma^{\rm HL}_{\rm th}$ & $\sigma^{\rm GT}_{\rm th}$ \\",
         r"\colrule"]
worst = 0.0
for key, label, suf in FUNCS:
    first = True
    for lk, lname in LIKS:   # Set A with the FINAL settings (2026-10-19): Q term, test errors, GT = Set A six
        vals, rh = stats(RP.posterior(key, "setA", lk)); worst = max(worst, rh)
        lines.append(f"{label if lk == 't4gtt4' else ''} & {'A' if lk == 't4gtt4' else ''} & {lname} & " + " & ".join(vals) + r" \\")
    for sname, skey in SETS[key]:
        if sname == "L10" and config.select_hl_nuclei(skey) == config.select_hl_nuclei(SETS[key][0][1]):
            lines.append(r" & L10 & & \multicolumn{4}{l}{same set as G10} \\")
            continue
        for lk, lname in LIKS:
            d = RP.posterior(key, {"Full": "full"}.get(sname, sname), lk)
            if not os.path.isdir(d):
                print("MISSING", d); continue
            vals, rh = stats(d); worst = max(worst, rh)
            lines.append(f" & {sname if lk == 't4gtt4' else ''} & {lname} & " + " & ".join(vals) + r" \\")
    lines.append(r"\colrule")
lines.pop()
lines += [r"\end{tabular}", r"\end{ruledtabular}", r"\end{table*}"]
open(OUT, "w").write("\n".join(lines) + "\n")
print("wrote", os.path.abspath(OUT), f"| max r_hat over all runs {worst:.3f}")
